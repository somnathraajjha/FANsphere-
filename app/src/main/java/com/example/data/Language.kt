    JAPANESE("日本語", "ja"),
    KOREAN("한국어", "ko"),
    RUSSIAN("Русский", "ru"),
    TURKISH("Türkçe", "tr"),
    PERSIAN("فارسی", "fa"),
    THAI("ไทย", "th"),
    VIETNAMESE("Tiếng Việt", "vi"),
    INDONESIAN("Bahasa Indonesia", "id"),
    MALAY("Bahasa Melayu", "ms"),
    POLISH("Polski", "pl"),
    UKRAINIAN("Українська", "uk"),
    HEBREW("עברית", "he"),
    SWEDISH("Svenska", "sv");

    companion object {
        fun fromCode(code: String): Language {
            return values().find { it.code.lowercase() == code.lowercase() } ?: ENGLISH
        }
    }
}

